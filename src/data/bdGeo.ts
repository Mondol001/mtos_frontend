export interface DivisionOption {
  name: string;
  moujaCount: number;
}

export interface DistrictOption {
  name: string;
  moujaCount: number;
}

export interface UpazilaOption {
  name: string;
  moujaCount: number;
}

export function getDivisionOptions(moujas: Mouja[]): DivisionOption[] {
  const counts = new Map<string, number>();
  for (const d of BD_DIVISIONS) counts.set(d.name, 0);
  for (const m of moujas) {
    const div = m.division?.trim();
    if (div) counts.set(div, (counts.get(div) || 0) + 1);
  }
  return Array.from(counts.entries()).map(([name, moujaCount]) => ({
    name,
    moujaCount,
  }));
}

export function getDistrictOptions(
  division: string,
  moujas: Mouja[]
): DistrictOption[] {
  const divObj = BD_DIVISIONS.find((d) => d.name === division);
  const counts = new Map<string, number>();
  if (divObj) {
    for (const dist of divObj.districts) counts.set(dist.name, 0);
  }
  for (const m of moujas) {
    if (m.division?.trim() === division && m.district?.trim()) {
      const dist = m.district.trim();
      counts.set(dist, (counts.get(dist) || 0) + 1);
    }
  }
  return Array.from(counts.entries()).map(([name, moujaCount]) => ({
    name,
    moujaCount,
  }));
}

export function getUpazilaOptions(
  division: string,
  district: string,
  moujas: Mouja[]
): UpazilaOption[] {
  const divObj = BD_DIVISIONS.find((d) => d.name === division);
  const distObj = divObj?.districts.find((dt) => dt.name === district);
  const counts = new Map<string, number>();
  if (distObj) {
    for (const up of distObj.upazilas) counts.set(up, 0);
  }
  for (const m of moujas) {
    if (
      m.division?.trim() === division &&
      m.district?.trim() === district &&
      m.upazila?.trim()
    ) {
      const up = m.upazila.trim();
      counts.set(up, (counts.get(up) || 0) + 1);
    }
  }
  return Array.from(counts.entries()).map(([name, moujaCount]) => ({
    name,
    moujaCount,
  }));
}

export function filterMoujasByLocation(
  moujas: Mouja[],
  division: string,
  district: string,
  upazila: string,
  moujaOrJlQuery = ''
): Mouja[] {
  const qNorm = bnToEnDigits(moujaOrJlQuery).trim().toLowerCase();
  return moujas.filter((m) => {
    if (division && m.division?.trim() !== division) return false;
    if (district && m.district?.trim() !== district) return false;
    if (upazila && m.upazila?.trim() !== upazila) return false;
    if (!qNorm) return true;
    const nameMatch = m.name.toLowerCase().includes(qNorm);
    const jlMatch = bnToEnDigits(m.jlNo).toLowerCase().includes(qNorm);
    return nameMatch || jlMatch;
  });
}
